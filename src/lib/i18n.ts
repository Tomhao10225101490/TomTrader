const DICT: Record<Locale, Record<StringKey, string>> = { en, zh };

export function t(locale: Locale, key: StringKey, vars?: Record<string, string | number>): string {
  let out = DICT[locale][key] ?? DICT.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) out = out.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
  }
  return out;
}

